#!/usr/bin/env node
/**
 * ATL3-V01 (#1295) — Host mirror of the committed Golden Krypta forge run.
 * Location: scripts/atl3-v01-golden-krypta-forge.mjs
 *
 * The Host may not import frontend domains, so the committed Dungeon-Forge
 * crypt (`buildGoldenCryptCanvas` / `buildGoldenCryptDungeonMeta`) is mirrored
 * as static data in `server/src/bootstrap/dornhain-golden-krypta-forge.ts`.
 * `--write` regenerates the mirror; default mode checks parity (exit 1 on drift).
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { createJiti } from 'jiti';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const jiti = createJiti(import.meta.url, { esmResolve: true });
const golden = jiti(join(root, 'src/domains/world/atlas/dornhain-golden-hierarchy.ts'));
const OUT = join(root, 'server/src/bootstrap/dornhain-golden-krypta-forge.ts');

const doc = golden.buildGoldenCryptCanvas();
const meta = golden.buildGoldenCryptDungeonMeta();
const rows = (items) => items.map((it) => `    ${JSON.stringify(it)},`).join('\n');

const src = `/**
 * dornhain-golden-krypta-forge — committed Dungeon-Forge Golden Krypta (Host mirror).
 * Location: server/src/bootstrap/dornhain-golden-krypta-forge.ts
 *
 * GENERATED by \`node scripts/atl3-v01-golden-krypta-forge.mjs --write\` from the FE
 * domain builder \`buildGoldenCryptCanvas\` (src/domains/world/atlas/dornhain-golden-hierarchy.ts).
 * Do not edit by hand — parity is checked in test-gate (ATL3-V01 #1295).
 * Forge params: ${JSON.stringify(golden.GOLDEN_KRYPTA_FORGE_PARAMS)}
 */

export const GOLDEN_KRYPTA_FORGE_DUNGEON_META = ${JSON.stringify(meta)} as const;

export const GOLDEN_KRYPTA_FORGE_FEATURES = {
  rooms: [
${rows(doc.rooms)}
  ],
  walls: [
${rows(doc.walls)}
  ],
  doors: [
${rows(doc.doors ?? [])}
  ],
  objects: [
${rows(doc.objects)}
  ],
} as const;
`;

if (process.argv.includes('--write')) {
  writeFileSync(OUT, src);
  console.log(`wrote ${OUT}`);
} else {
  const cur = readFileSync(OUT, 'utf8');
  if (cur !== src) {
    console.error('Golden Krypta Host mirror drifted — run: node scripts/atl3-v01-golden-krypta-forge.mjs --write');
    process.exit(1);
  }
  console.log('atl3-v01 golden krypta host mirror: PASS');
}
