#!/usr/bin/env node
/**
 * no-committed-anon-jwt-check — #672 ban hardcoded hosted JWTs in src.
 * Location: scripts/no-committed-anon-jwt-check.mjs
 */
import { readdirSync, readFileSync, statSync } from 'node:fs';
import { join, relative } from 'node:path';
import { fileURLToPath } from 'node:url';
import process from 'node:process';

const root = join(fileURLToPath(new URL('..', import.meta.url)));
const srcRoot = join(root, 'src');
const jwtRe = /eyJhbGciOiJIUzI1NiIsInR5cCI6IkpXVCJ9\.[A-Za-z0-9_-]+\.[A-Za-z0-9_-]+/g;
const hostedRefs = ['dnhotyjazjnhneqbqocq', 'vjpfbedynctazvwywlqj'];

function walk(dir, acc = []) {
  for (const entry of readdirSync(dir)) {
    const full = join(dir, entry);
    const st = statSync(full);
    if (st.isDirectory()) {
      if (entry === 'node_modules' || entry === 'dist') continue;
      walk(full, acc);
      continue;
    }
    if (/\.(ts|tsx|js|jsx|mjs|cjs|md)$/.test(entry)) acc.push(full);
  }
  return acc;
}

let failures = 0;
for (const file of walk(srcRoot)) {
  const text = readFileSync(file, 'utf8');
  const rel = relative(root, file);
  const matches = text.match(jwtRe);
  if (matches?.length) {
    failures += 1;
    console.error(`FAIL: JWT literal in ${rel}`);
  }
  // Autogenerated Figma Make stubs may mention a dashboard URL; ban JWTs only there.
  const allowHostedRefComment =
    rel.replace(/\\/g, '/') === 'archive/supabase-legacy/src-supabase/functions/server/kv_store.tsx';
  for (const ref of hostedRefs) {
    if (text.includes(ref) && !allowHostedRefComment) {
      failures += 1;
      console.error(`FAIL: hosted project ref ${ref} in ${rel}`);
    }
  }
}

const supabaseTs = readFileSync(join(root, 'src/lib/supabase.ts'), 'utf8');
if (/^\s*import\s+.*@supabase\/supabase-js/m.test(supabaseTs) || /\bcreateClient\s*\(/.test(supabaseTs)) {
  failures += 1;
  console.error('FAIL: supabase.ts must stay SDK-free after CUT-21 (no createClient)');
}
if (/publicAnonKey|from ['\"].*utils\/supabase\/info/.test(supabaseTs)) {
  failures += 1;
  console.error('FAIL: supabase.ts must not fall back to info.tsx JWT');
}
if (jwtRe.test(supabaseTs)) {
  failures += 1;
  console.error('FAIL: supabase.ts must not contain JWT literals');
}

const info = readFileSync(join(root, 'archive/supabase-legacy/src-utils-supabase/info.tsx'), 'utf8');
if (jwtRe.test(info)) {
  failures += 1;
  console.error('FAIL: info.tsx still contains JWT');
}

const docs = join(root, 'docs/ops/rotate-hosted-anon-keys.md');
try {
  const d = readFileSync(docs, 'utf8');
  for (const ref of hostedRefs) {
    if (!d.includes(ref)) {
      failures += 1;
      console.error(`FAIL: rotation docs must mention ${ref}`);
    }
  }
} catch {
  failures += 1;
  console.error('FAIL: missing docs/ops/rotate-hosted-anon-keys.md');
}

if (failures) {
  console.error(`no-committed-anon-jwt-check: ${failures} failure(s)`);
  process.exit(1);
}
console.log('✓ no-committed-anon-jwt-check OK');
