#!/usr/bin/env node
/**
 * sync-default-world-host-seed — Regenerates Host mirror of the calibrated
 * Bottom-Up Default World (`server/src/bootstrap/dornhain-default-world-mirror.ts`)
 * from FE domain `src/domains/world/atlas/atlas-default-world.ts` without
 * introducing any FE imports into `server/` (architecture boundary).
 */
import { mkdtempSync, rmSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { dirname, join } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';
import { buildSync } from 'esbuild';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const tmp = mkdtempSync(join(tmpdir(), 'sync-default-world-'));
const outfile = join(tmp, 'dw.mjs');

buildSync({
  entryPoints: [join(root, 'src/domains/world/atlas/atlas-default-world.ts')],
  bundle: true,
  platform: 'node',
  format: 'esm',
  outfile,
});

const dw = await import(pathToFileURL(outfile).href);
const bundle = dw.buildCalibratedDefaultWorld();

const STABLE_MAP_IDS = {
  'dornhain.map.continent.westmark': 'dh-map-continent-westmark',
  'dornhain.map.country.westmark': 'dh-map-country-westmark',
  'dornhain.map.place.dornhain': 'dh-map-place-dornhain',
  'dornhain.map.loc.tavern': 'dh-map-loc-tavern',
  'dornhain.map.loc.crypt': 'dh-map-loc-crypt',
};

const STABLE_PLACE_IDS = {
  'continent.westmark': 'dh-place-continent-westmark',
  'country.westmark': 'dh-place-country-westmark',
  'place.dornhain': 'dh-place-dornhain',
  'dornhain.marktplatz': 'dh-place-square',
  'dornhain.whisper-road': 'dh-place-whisper',
  'loc.tavern': 'dh-place-tavern',
  'loc.crypt': 'dh-place-crypt',
};

function stableMapId(seedKey) {
  return STABLE_MAP_IDS[seedKey] ?? `dh-map-${seedKey.replace(/^dornhain\.map\./, '').replace(/\./g, '-')}`;
}

function stablePlaceId(seedKey) {
  return STABLE_PLACE_IDS[seedKey] ?? `dh-place-${seedKey.replace(/\./g, '-')}`;
}

const mapEntries = bundle.maps.map((m) => ({
  stableId: stableMapId(m.seedKey),
  seedKey: m.seedKey,
  placeSeedKey: m.placeSeedKey,
  title: m.title,
  kind: m.kind,
  parentMapSeedKey: m.parentMapSeedKey,
  parentAnchor: m.parentAnchor,
  canvas: m.buildCanvas(),
  ...(m.buildDungeonMeta ? { dungeonMeta: m.buildDungeonMeta() } : {}),
}));

const placeEntries = bundle.places.map((p) => ({
  stableId: stablePlaceId(p.seedKey),
  seedKey: p.seedKey,
  name: p.name,
  kind: p.kind,
  description: p.description,
  parentSeedKey: p.parentSeedKey,
  anchor: p.anchor,
  sortOrder: p.sortOrder,
}));

const out = `/**
 * dornhain-default-world-mirror — GENERATED Host mirror of calibrated Bottom-Up Default World.
 * Location: server/src/bootstrap/dornhain-default-world-mirror.ts
 *
 * Generated by \`node scripts/sync-default-world-host-seed.mjs\` from FE domain
 * \`src/domains/world/atlas/atlas-default-world.ts\` (no FE imports in server/).
 */

export const DEFAULT_WORLD_ROOT_METERS_PER_UNIT = ${JSON.stringify(bundle.rootMetersPerUnit)} as const;

export const DEFAULT_WORLD_ROOT_CANVAS = ${JSON.stringify(bundle.rootDoc, null, 2)} as const;

export const DEFAULT_WORLD_PLACE_SEEDS = ${JSON.stringify(placeEntries, null, 2)} as const;

export const DEFAULT_WORLD_MAP_DATA = ${JSON.stringify(mapEntries, null, 2)} as const;
`;

const target = join(root, 'server/src/bootstrap/dornhain-default-world-mirror.ts');
writeFileSync(target, out, 'utf8');
rmSync(tmp, { recursive: true, force: true });
console.log(`✓ wrote ${target} (${mapEntries.length} child maps, ${placeEntries.length} places)`);
